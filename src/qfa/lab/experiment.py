"""
One MatBench fold of the QFA-Net lab pipeline (NumPy only).

Branch used here: descriptor branch (Magpie 132 + symmetry 8 -> MI selection -> MLP).
On top of it, the QFA-Net quantum part, exactly as in the full model:
    phase A  classical model (early stopping on validation)
    phase B  quantum residual head on the frozen classical latent (y = y_c + r, r starts at 0)
    phase C  ablation pruning of circuit rotations, with fine-tuning, validation-guarded
    phase D  Quantum-Train: the classical MLP's weights generated by a 13-17 qubit QNN
Controls: RandomForest on all features, classical model alone, and an MLP residual head
with about the same number of parameters as the quantum head.

The test fold is used only for the final scores. All choices use the validation split
(10 % of the training fold).
"""
import time
from typing import Dict, List, Tuple

import numpy as np
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.feature_selection import mutual_info_classif, mutual_info_regression
from sklearn.metrics import roc_auc_score

from .data import split_train_val
from .nn import MLP, AdamW, loss_and_grad, silu, silu_grad
from .qsim import QuantumHead
from .qt import QTGenerator

# ----------------------------------------------------------------------------- policy
TIERS = [  # (max n_train, name, hidden, batch, epochs A, patience A, epochs B, seeds, prune limit, QT)
    (1000, "tiny", 64, 32, 400, 60, 150, 5, 0.60, True),
    (10000, "small", 128, 64, 200, 30, 40, 3, 0.50, True),
    (30000, "medium", 256, 256, 100, 15, 12, 2, 0.40, False),
    (10 ** 9, "large", 256, 512, 40, 6, 4, 1, 0.30, False),
]


def policy(n_train: int) -> Dict:
    for lim, name, hid, bs, ea, pa, eb, seeds, prune, qt in TIERS:
        if n_train <= lim:
            return {"tier": name, "hidden": hid, "batch": bs, "epochs_a": ea, "patience_a": pa,
                    "epochs_b": eb, "seeds": seeds, "prune_limit": prune, "qt": qt,
                    "k": int(np.clip(4 * np.sqrt(n_train), 32, 10 ** 6))}


# ----------------------------------------------------------------------------- metrics
def metric(task_type: str, y: np.ndarray, pred: np.ndarray) -> float:
    if task_type == "regression":
        return float(np.mean(np.abs(y - pred)))
    return float(roc_auc_score(y, pred))


def better(task_type: str, a: float, b: float) -> bool:
    return a < b if task_type == "regression" else a > b


# ----------------------------------------------------------------------------- preprocessing
def select_features(X: np.ndarray, y: np.ndarray, task_type: str, k: int, seed: int) -> np.ndarray:
    """MODNet-style: rank by mutual information with the target, skip near-duplicates."""
    std = X.std(axis=0)
    ok = np.where(std > 1e-12)[0]
    rng = np.random.default_rng(seed)
    rows = rng.choice(len(X), size=min(len(X), 8000), replace=False)
    fn = mutual_info_regression if task_type == "regression" else mutual_info_classif
    mi = fn(X[rows][:, ok], y[rows], random_state=seed)
    order = ok[np.argsort(-mi)]
    Z = (X[rows] - X[rows].mean(0)) / (std + 1e-12)
    chosen: List[int] = []
    for j in order:
        if len(chosen) >= k:
            break
        if chosen and np.max(np.abs(Z[:, chosen].T @ Z[:, j]) / len(rows)) > 0.95:
            continue
        chosen.append(int(j))
    return np.array(chosen)


class Prep:
    def __init__(self, X, y, task_type, cols):
        self.cols = cols
        self.mu = X[:, cols].mean(0)
        self.sd = X[:, cols].std(0) + 1e-9
        self.task_type = task_type
        if task_type == "regression":
            self.ym, self.ys = float(y.mean()), float(y.std() + 1e-12)
        else:
            self.ym, self.ys = 0.0, 1.0

    def x(self, X):
        return np.clip((X[:, self.cols] - self.mu) / self.sd, -6, 6)

    def y(self, y):
        return (y - self.ym) / self.ys

    def inv(self, p):
        return p * self.ys + self.ym


# ----------------------------------------------------------------------------- phase A
def predict_mlp(net: MLP, X: np.ndarray, bs: int = 4096) -> Tuple[np.ndarray, np.ndarray]:
    outs, hs = [], []
    for i in range(0, len(X), bs):
        o, h = net.forward(X[i:i + bs], keep=False)
        outs.append(o[:, 0])
        hs.append(h)
    return np.concatenate(outs), np.concatenate(hs)


def train_classical(Xtr, ytr, Xva, yva, cfg, task_type, seed, generator: QTGenerator = None,
                    lr: float = 2e-3):
    """Trains the MLP directly, or (generator given) trains the QT generator that writes its weights."""
    rng = np.random.default_rng(seed)
    net = MLP([Xtr.shape[1], cfg["hidden"], cfg["hidden"] // 2, 1], rng)
    if generator is None:
        opt = AdamW(net.params, lr=lr, wd=1e-4)
    else:
        gparams = [generator.phi, *generator.mapper.params, generator.scales]
        opt = AdamW(gparams, lr=5e-3, wd=0.0)
        net.set_flat(generator.generate())
    best = (np.inf if task_type == "regression" else -np.inf, None, 0)
    patience = cfg["patience_a"] * (2 if generator is not None else 1)
    epochs = cfg["epochs_a"] * (2 if generator is not None else 1)
    for ep in range(epochs):
        perm = rng.permutation(len(Xtr))
        for i in range(0, len(perm), cfg["batch"]):
            b = perm[i:i + cfg["batch"]]
            if generator is not None:
                net.set_flat(generator.generate())
            out, _ = net.forward(Xtr[b])
            _, g = loss_and_grad(out[:, 0], ytr[b], task_type)
            grads, _ = net.backward(g[:, None])
            if generator is None:
                opt.step(net.params, grads)
            else:
                gflat = np.concatenate([gr.ravel() for gr in grads])
                g_phi, g_map, g_s = generator.backward(gflat)
                opt.step(gparams, [g_phi, *g_map, g_s])
        if generator is not None:
            net.set_flat(generator.generate())
        pv, _ = predict_mlp(net, Xva)
        m = metric(task_type, yva, pv) if task_type == "classification" else float(np.mean(np.abs(pv - yva)))
        if better(task_type, m, best[0]):
            best = (m, [p.copy() for p in net.params], ep)
        elif ep - best[2] > patience:
            break
    net.params = best[1]
    return net, best[0], best[2]


# ----------------------------------------------------------------------------- phase B heads
class QHead:
    """latent h -> Linear -> pi*tanh -> 8-qubit circuit -> 16 numbers -> Linear (zero init) -> r"""

    def __init__(self, d_in, rng, n_qubits=8, n_layers=3):
        self.enc = MLP([d_in, n_qubits], rng)
        self.circ = QuantumHead(n_qubits, n_layers, rng, init_scale=0.1)
        self.circ.drop_dead()
        self.wr = np.zeros(self.circ.n_outputs)
        self.br = np.zeros(1)

    def params(self):
        return [*self.enc.params, self.circ.a, self.wr, self.br]

    def n_trainable(self):
        return self.enc.n_params + self.circ.n_active() + self.wr.size + 1

    def forward(self, h, keep=True):
        u, _ = self.enc.forward(h, keep=keep)
        t = np.tanh(u)
        x = np.pi * t
        o, psi = self.circ.forward(x)
        if keep:
            self._c = (t, x, o, psi)
        return o @ self.wr + self.br[0]

    def backward(self, g):
        t, x, o, psi = self._c
        g_wr = o.T @ g
        g_br = np.array([g.sum()])
        go = g[:, None] * self.wr[None, :]
        da, dx = self.circ.backward(x, psi, go)
        du = dx * np.pi * (1 - t ** 2)
        g_enc, dh = self.enc.backward(du)
        return [*g_enc, da, g_wr, g_br], dh


class MLPHead:
    """Classical control of similar size: h -> 8 (tanh) -> 16 (SiLU) -> 1 (zero init)."""

    def __init__(self, d_in, rng):
        self.l1 = MLP([d_in, 8], rng)
        self.l2 = MLP([8, 16, 1], rng, last_zero=True)

    def params(self):
        return [*self.l1.params, *self.l2.params]

    def n_trainable(self):
        return self.l1.n_params + self.l2.n_params

    def forward(self, h, keep=True):
        u, _ = self.l1.forward(h, keep=keep)
        t = np.tanh(u)
        if keep:
            self._t = t
        o, _ = self.l2.forward(t, keep=keep)
        return o[:, 0]

    def backward(self, g):
        g2, gt = self.l2.backward(g[:, None])
        g1, dh = self.l1.backward(gt * (1 - self._t ** 2))
        return [*g1, *g2], dh


class Joint:
    """Classical net (direct weights, or weights written by a QT generator) + residual head.
    pred = y_c(x) + r(h(x)). Classical part trains with a small learning rate, head with a larger one."""

    def __init__(self, net: MLP, head, generator: QTGenerator = None, lr_head=1e-2, lr_net=5e-4):
        self.net, self.head, self.gen = net, head, generator
        self.hp = head.params()
        self.opt_h = AdamW(self.hp, lr=lr_head, wd=0.0)
        if generator is None:
            self.np_ = net.params
            self.opt_n = AdamW(self.np_, lr=lr_net, wd=1e-4)
        else:
            self.np_ = [generator.phi, *generator.mapper.params, generator.scales]
            self.opt_n = AdamW(self.np_, lr=lr_net * 2, wd=0.0)

    def predict(self, X, bs=2048):
        if self.gen is not None:
            self.net.set_flat(self.gen.generate())
        out = []
        for i in range(0, len(X), bs):
            o, h = self.net.forward(X[i:i + bs], keep=False)
            out.append(o[:, 0] + self.head.forward(h, keep=False))
        return np.concatenate(out)

    def step(self, Xb, yb, task_type):
        if self.gen is not None:
            self.net.set_flat(self.gen.generate())
        o, h = self.net.forward(Xb)
        pred = o[:, 0] + self.head.forward(h)
        _, g = loss_and_grad(pred, yb, task_type)
        gh, dh = self.head.backward(g)
        self.opt_h.step(self.hp, gh)
        gn, _ = self.net.backward(g[:, None], ghidden=dh)
        if self.gen is None:
            self.opt_n.step(self.np_, gn)
        else:
            gp, gm, gs = self.gen.backward(np.concatenate([x.ravel() for x in gn]))
            self.opt_n.step(self.np_, [gp, *gm, gs])
        if isinstance(self.head, QHead):
            self.head.circ.a[~self.head.circ.mask] = 0.0

    def state(self):
        return [p.copy() for p in self.hp + self.np_]

    def load(self, st):
        for p, q in zip(self.hp + self.np_, st):
            p[...] = q


def train_joint(j: Joint, Xtr, ytr, Xva, yva, cfg, task_type, seed, epochs=None):
    rng = np.random.default_rng(seed + 77)
    def val():
        p = j.predict(Xva)
        return metric(task_type, yva, p) if task_type == "classification" else float(np.mean(np.abs(p - yva)))
    best_m, best_st, best_ep = val(), j.state(), -1   # epoch 0 = the classical twin (r = 0)
    for ep in range(epochs or cfg["epochs_b"]):
        perm = rng.permutation(len(Xtr))
        for i in range(0, len(perm), cfg["batch"]):
            b = perm[i:i + cfg["batch"]]
            j.step(Xtr[b], ytr[b], task_type)
        m = val()
        if better(task_type, m, best_m):
            best_m, best_st, best_ep = m, j.state(), ep
    j.load(best_st)
    return best_m, best_ep


# ----------------------------------------------------------------------------- phase C
def prune_joint(j: Joint, Xtr, ytr, Xva, yva, cfg, task_type, seed, tol=0.02):
    """Iterative ablation pruning of circuit rotations: switch each active angle off (angle 0 =
    identity), remove the 25 % whose removal hurts validation least, fine-tune, and stop before
    validation gets worse than (1 + tol) x the dense hybrid, or at the tier's sparsity limit."""
    circ = j.head.circ
    def val():
        p = j.predict(Xva)
        return metric(task_type, yva, p) if task_type == "classification" else float(np.mean(np.abs(p - yva)))
    dense = val()
    limit = dense * (1 + tol) if task_type == "regression" else dense * (1 - tol)
    n_start = circ.n_active()
    max_pruned = int(np.floor(cfg["prune_limit"] * n_start))
    history = [(n_start, dense)]
    while n_start - circ.n_active() < max_pruned:
        active = list(zip(*np.where(circ.mask)))
        scores = []
        for idx in active:
            old = circ.a[idx]
            circ.a[idx] = 0.0
            circ.mask[idx] = False
            scores.append(val())
            circ.mask[idx] = True
            circ.a[idx] = old
        order = np.argsort(scores) if task_type == "regression" else np.argsort(-np.array(scores))
        n_cut = min(max(1, int(0.25 * len(active))), max_pruned - (n_start - len(active)))
        saved = (j.state(), circ.mask.copy())
        for k in order[:n_cut]:
            circ.mask[active[k]] = False
            circ.a[active[k]] = 0.0
        train_joint(j, Xtr, ytr, Xva, yva, cfg, task_type, seed, epochs=max(3, cfg["epochs_b"] // 4))
        m = val()
        if not (m <= limit if task_type == "regression" else m >= limit):
            j.load(saved[0])
            circ.mask[...] = saved[1]
            break
        history.append((circ.n_active(), m))
    return dense, history


# ----------------------------------------------------------------------------- one fold
def run_fold(data: Dict, fold: int, seeds: int = None, log=print) -> Dict:
    t0 = time.time()
    tt = data["type"]
    test_idx = data["folds"][fold]
    train_all = np.setdiff1d(np.arange(len(data["y"])), test_idx)
    cfg = policy(len(train_all))
    n_seeds = seeds or cfg["seeds"]
    X, y = data["X"], data["y"]
    ytest = y[test_idx]
    preds = {k: [] for k in ["classical", "hybrid", "hybrid_pruned", "mlp_residual", "qt_classical",
                             "qt_hybrid_pruned"]}
    info = {"tier": cfg["tier"], "n_train": int(len(train_all)), "seeds": n_seeds, "per_seed": []}
    # RandomForest sanity baseline on all features
    rf = (RandomForestRegressor if tt == "regression" else RandomForestClassifier)(
        n_estimators=300, n_jobs=2, random_state=0, min_samples_leaf=1)
    rf.fit(X[train_all], y[train_all])
    prf = rf.predict(X[test_idx]) if tt == "regression" else rf.predict_proba(X[test_idx])[:, 1]
    for s in range(n_seeds):
        tr, va = split_train_val(train_all, seed=s)
        cols = select_features(X[tr], y[tr], tt, min(cfg["k"], X.shape[1]), seed=s)
        P = Prep(X[tr], y[tr], tt, cols)
        Xtr, Xva, Xte = P.x(X[tr]), P.x(X[va]), P.x(X[test_idx])
        ytr, yva = P.y(y[tr]), P.y(y[va])
        net, vA, epA = train_classical(Xtr, ytr, Xva, yva, cfg, tt, seed=s)
        yc_tr, H_tr = predict_mlp(net, Xtr)
        yc_va, H_va = predict_mlp(net, Xva)
        yc_te, H_te = predict_mlp(net, Xte)
        rec = {"seed": s, "k": int(len(cols)), "classical_params": net.n_params, "val_classical": vA, "epochs_a": epA}
        preds["classical"].append(yc_te)
        import copy
        # quantum residual (dense), trained jointly with the classical net
        qh = QHead(cfg["hidden"] // 2, np.random.default_rng(s + 5))
        jq = Joint(copy.deepcopy(net), qh)
        vB, epB = train_joint(jq, Xtr, ytr, Xva, yva, cfg, tt, s)
        preds["hybrid"].append(jq.predict(Xte))
        rec.update({"val_hybrid": vB, "epoch_b": epB, "gates_dense": qh.circ.gate_counts(),
                    "qhead_params_dense": qh.n_trainable()})
        # pruning
        dense_v, hist = prune_joint(jq, Xtr, ytr, Xva, yva, cfg, tt, s)
        preds["hybrid_pruned"].append(jq.predict(Xte))
        rec.update({"prune_history": hist, "gates_pruned": qh.circ.gate_counts(),
                    "qhead_params_pruned": qh.n_trainable(), "mask": qh.circ.mask.astype(int).tolist()})
        # classical control head of similar size, same joint training
        mh = MLPHead(cfg["hidden"] // 2, np.random.default_rng(s + 9))
        jm = Joint(copy.deepcopy(net), mh, lr_head=5e-3)
        vM, _ = train_joint(jm, Xtr, ytr, Xva, yva, cfg, tt, s)
        preds["mlp_residual"].append(jm.predict(Xte))
        rec.update({"val_mlp_residual": vM, "mlp_head_params": mh.n_trainable()})
        # Quantum-Train: classical weights generated by a QNN, then the pruned quantum head on top
        if cfg["qt"]:
            shapes = [p.shape for p in net.params]
            gen = QTGenerator(shapes, np.random.default_rng(s + 11), n_layers=8, hidden=16)
            qnet, vQ, epQ = train_classical(Xtr, ytr, Xva, yva, cfg, tt, seed=s, generator=gen)
            preds["qt_classical"].append(predict_mlp(qnet, Xte)[0])
            qh2 = QHead(cfg["hidden"] // 2, np.random.default_rng(s + 5))
            qh2.circ.mask[...] = qh.circ.mask
            qh2.circ.a[~qh2.circ.mask] = 0.0
            jt = Joint(qnet, qh2, generator=gen)
            vQH, _ = train_joint(jt, Xtr, ytr, Xva, yva, cfg, tt, s)
            preds["qt_hybrid_pruned"].append(jt.predict(Xte))
            rec.update({"qt_qubits": gen.n, "qt_generated": gen.P, "qt_trained": gen.n_trainable,
                        "val_qt_classical": vQ, "val_qt_hybrid_pruned": vQH, "qt_epochs": epQ,
                        "qt_hybrid_trained": gen.n_trainable + qh2.n_trainable()})
        rec["inv"] = (P.ym, P.ys)
        info["per_seed"].append(rec)
        log(f"  seed {s}: val A {vA:.4f} B {vB:.4f} pruned {hist[-1][1]:.4f} "
            f"({hist[-1][0]}/{hist[0][0]} angles) mlp {vM:.4f} [{time.time() - t0:.0f}s]")
    scores = {}
    for k, lst in preds.items():
        if not lst:
            continue
        p = np.mean([info["per_seed"][i]["inv"][0] + v * info["per_seed"][i]["inv"][1]
                     for i, v in enumerate(lst)], axis=0) if tt == "regression" else np.mean(lst, axis=0)
        scores[k] = metric(tt, ytest, p)
    scores["rf"] = metric(tt, ytest, prf)
    info["test"] = scores
    info["seconds"] = time.time() - t0
    return info


def run_qt_control(data: Dict, fold: int, seeds: int = 3, log=print) -> Dict:
    """Is Quantum-Train's effect quantum? Same mapping MLP, with the QNN probabilities (quantum)
    or without them (none). Classical MLP only, no residual head."""
    tt = data["type"]
    test_idx = data["folds"][fold]
    train_all = np.setdiff1d(np.arange(len(data["y"])), test_idx)
    cfg = policy(len(train_all))
    X, y = data["X"], data["y"]
    preds = {"qt_quantum": [], "qt_none": [], "direct": []}
    info = {"per_seed": []}
    for s in range(seeds):
        tr, va = split_train_val(train_all, seed=s)
        cols = select_features(X[tr], y[tr], tt, min(cfg["k"], X.shape[1]), seed=s)
        P = Prep(X[tr], y[tr], tt, cols)
        Xtr, Xva, Xte = P.x(X[tr]), P.x(X[va]), P.x(X[test_idx])
        ytr, yva = P.y(y[tr]), P.y(y[va])
        rec = {"seed": s}
        net, vD, _ = train_classical(Xtr, ytr, Xva, yva, cfg, tt, seed=s)
        preds["direct"].append(P.inv(predict_mlp(net, Xte)[0]))
        for mode in ("quantum", "none"):
            shapes = [p.shape for p in net.params]
            gen = QTGenerator(shapes, np.random.default_rng(s + 11), n_layers=8, hidden=16, mode=mode)
            qnet, v, ep = train_classical(Xtr, ytr, Xva, yva, cfg, tt, seed=s, generator=gen)
            preds[f"qt_{mode}"].append(P.inv(predict_mlp(qnet, Xte)[0]))
            rec[f"val_{mode}"], rec[f"trained_{mode}"], rec[f"epochs_{mode}"] = v, gen.n_trainable, ep
        rec["val_direct"] = vD
        info["per_seed"].append(rec)
        log(f"  seed {s}: {rec}")
    info["test"] = {k: metric(tt, y[test_idx], np.mean(v, axis=0)) for k, v in preds.items()}
    return info
