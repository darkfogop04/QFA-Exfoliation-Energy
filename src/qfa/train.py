"""
Training of the full QFA-Net on one MatBench fold (PyTorch). Same phases as the lab
(src/qfa/lab/experiment.py), which was run and checked in NumPy:

  A  classical: depth mixer + graph adapter + descriptor branch + head (quantum head off: r = 0)
  B  quantum residual: circuit head added, trained jointly; epoch 0 = the classical twin
  C  ablation pruning of circuit rotations, validation-guarded
  D  Quantum-Train (tiny/small tiers): the classical weights are generated by a QNN
Controls per seed: classical twin, MLP residual of similar size, RandomForest on descriptors.
"""
import copy
import time
from typing import Dict, List

import numpy as np
import torch
from torch.func import functional_call

from .data import CLASSIFICATION, collate
from .lab.data import split_train_val
from .lab.experiment import Prep, metric, policy, select_features
from .model import QFANet
from .quantum_torch import QTGeneratorTorch

# names of classical tensors that Quantum-Train generates (everything except mixing
# weights and LayerNorms, which stay directly trainable)
def qt_names(model: QFANet) -> List[str]:
    return [n for n, p in model.named_parameters()
            if not n.startswith(("q_in", "circuit", "q_out", "ctrl")) and "mixer" not in n and "norm" not in n]


def _loss(pred, y, tt):
    if tt == "regression":
        return torch.mean(torch.abs(pred - y))
    return torch.nn.functional.binary_cross_entropy_with_logits(pred, y)


class Runner:
    def __init__(self, prep: Dict, desc: np.ndarray, y: np.ndarray, tt: str, cfg: Dict, device="cpu"):
        self.prep, self.desc, self.y, self.tt, self.cfg, self.device = prep, desc, y, tt, cfg, device

    def batches(self, rows, shuffle, rng, bs=None):
        rows = rng.permutation(rows) if shuffle else rows
        bs = bs or self.cfg["batch"]
        for i in range(0, len(rows), bs):
            r = rows[i:i + bs]
            yield collate(self.prep, r, self.desc, self.device), torch.tensor(self.y[r], dtype=torch.float32)

    def predict(self, model, rows, gen=None, names=None) -> np.ndarray:
        model.eval()
        out = []
        with torch.no_grad():
            params = gen.as_dict(names) if gen is not None else None
            for b, _ in self.batches(rows, False, None):
                p = functional_call(model, params, (b,), strict=False) if params else model(b)
                out.append(p.cpu().numpy())
        return np.concatenate(out)

    def val_score(self, model, rows, gen=None, names=None):
        p = self.predict(model, rows, gen, names)
        return metric(self.tt, self.y[rows], p) if self.tt == "classification" else float(np.mean(np.abs(p - self.y[rows])))

    def better(self, a, b):
        return a < b if self.tt == "regression" else a > b

    def fit(self, model, tr, va, groups, epochs, patience, seed, gen=None, names=None, max_minutes=None):
        """groups: list of (params, lr). Keeps the best validation state (epoch 0 included)."""
        rng = np.random.default_rng(seed)
        opt = torch.optim.AdamW([{"params": p, "lr": lr} for p, lr in groups], weight_decay=1e-4)
        mods = [model] + ([gen] if gen is not None else [])
        best = (self.val_score(model, va, gen, names), [copy.deepcopy(m.state_dict()) for m in mods], -1)
        t0 = time.time()
        for ep in range(epochs):
            model.train()
            # Quantum-Train regenerates every weight at each step, so it uses larger batches
            for b, yb in self.batches(tr, True, rng, bs=max(self.cfg["batch"], 256) if gen is not None else None):
                params = gen.as_dict(names) if gen is not None else None
                pred = functional_call(model, params, (b,), strict=False) if params else model(b)
                loss = _loss(pred, yb, self.tt)
                opt.zero_grad()
                loss.backward()
                opt.step()
                with torch.no_grad():
                    model.circuit.a[~model.circuit.mask] = 0.0
            v = self.val_score(model, va, gen, names)
            if self.better(v, best[0]):
                best = (v, [copy.deepcopy(m.state_dict()) for m in mods], ep)
            elif ep - best[2] > patience:
                break
            if max_minutes and (time.time() - t0) > 60 * max_minutes:
                break
        for m, st in zip(mods, best[1]):
            m.load_state_dict(st)
        return best[0], best[2]

    def prune(self, model, tr, va, seed, tol=0.02, gen=None, names=None):
        circ = model.circuit
        dense = self.val_score(model, va, gen, names)
        limit = dense * (1 + tol) if self.tt == "regression" else dense * (1 - tol)
        n0 = circ.n_active()
        max_cut = int(np.floor(self.cfg["prune_limit"] * n0))
        hist = [(n0, dense)]
        while n0 - circ.n_active() < max_cut:
            active = [tuple(i) for i in torch.nonzero(circ.mask).tolist()]
            scores = []
            for idx in active:
                old = circ.a.data[idx].clone()
                circ.mask[idx] = False
                circ.a.data[idx] = 0.0
                scores.append(self.val_score(model, va, gen, names))
                circ.mask[idx] = True
                circ.a.data[idx] = old
            order = np.argsort(scores) if self.tt == "regression" else np.argsort(-np.array(scores))
            n_cut = min(max(1, int(0.25 * len(active))), max_cut - (n0 - len(active)))
            saved = (copy.deepcopy(model.state_dict()), circ.mask.clone())
            for k in order[:n_cut]:
                circ.mask[active[k]] = False
                circ.a.data[active[k]] = 0.0
            self.fit(model, tr, va, [(model.quantum_parameters(), 1e-2), (model.classical_parameters(), 2e-4)],
                     max(3, self.cfg["epochs_b"] // 4), 10 ** 6, seed, gen, names)
            m = self.val_score(model, va, gen, names)
            if not (m <= limit if self.tt == "regression" else m >= limit):
                model.load_state_dict(saved[0])
                circ.mask.copy_(saved[1])
                break
            hist.append((circ.n_active(), m))
        return hist


def run_fold(task: str, prep: Dict, X_desc: np.ndarray, y: np.ndarray, test_idx: np.ndarray, seeds: int = None,
             quick: bool = False, max_minutes: float = None, device: str = "cpu", log=print,
             ablation: str = "none") -> Dict:
    t_start = time.time()
    tt = "classification" if task in CLASSIFICATION else "regression"
    n_all = len(y)
    train_all = np.setdiff1d(np.arange(n_all), test_idx)
    cfg = dict(policy(len(train_all)))
    if quick:
        cfg.update({"epochs_a": 3, "epochs_b": 2, "patience_a": 2, "seeds": 1})
    cfg["epochs_a_scaled"] = cfg["epochs_a"]
    n_seeds = seeds or cfg["seeds"]
    preds = {k: [] for k in ["classical", "hybrid", "hybrid_pruned", "mlp_residual", "qt_hybrid_pruned"]}
    info = {"task": task, "tier": cfg["tier"], "n_train": int(len(train_all)), "ablation": ablation, "per_seed": []}
    emb_layers = None
    if prep["structural"]:
        first = prep["emb"][prep["ids"][0]]
        emb_layers = first.shape[0]
    for s in range(n_seeds):
        torch.manual_seed(s)
        tr, va = split_train_val(train_all, seed=s)
        cols = select_features(X_desc[tr], y[tr], tt, min(cfg["k"], X_desc.shape[1]), seed=s)
        P = Prep(X_desc[tr], y[tr], tt, cols)
        desc = P.x(X_desc).astype(np.float32)
        ys = P.y(y).astype(np.float32)
        R = Runner(prep, desc, ys, tt, cfg, device)
        kw = dict(n_layers=emb_layers or 1, n_desc=len(cols), mode=prep.get("mode", "atoms"),
                  use_graph=prep["structural"], ablation=ablation)
        model = QFANet(**kw).to(device)
        t_phase = time.time()
        vA, eA = R.fit(model, tr, va, [(model.classical_parameters(), 1e-3)], cfg["epochs_a"],
                       cfg["patience_a"], s, max_minutes=max_minutes)
        inv = lambda p: P.inv(p) if tt == "regression" else p
        preds["classical"].append(inv(R.predict(model, test_idx)))
        rec = {"seed": s, "sec_classical": time.time() - t_phase, "val_classical": vA, "params": model.n_trainable(),
               "depth_weights": model.mixer.weights().tolist() if prep["structural"] and ablation != "last_layer" else None}
        # B: quantum residual
        t_phase = time.time()
        hyb = copy.deepcopy(model)
        vB, eB = R.fit(hyb, tr, va, [(hyb.quantum_parameters(), 1e-2), (hyb.classical_parameters(), 2e-4)],
                       cfg["epochs_b"], max(10, cfg["epochs_b"] // 3), s, max_minutes=max_minutes)
        preds["hybrid"].append(inv(R.predict(hyb, test_idx)))
        rec.update({"val_hybrid": vB, "gates_dense": hyb.circuit.gate_counts()})
        # C: pruning
        hist = R.prune(hyb, tr, va, s)
        preds["hybrid_pruned"].append(inv(R.predict(hyb, test_idx)))
        rec.update({"sec_hybrid_and_pruning": time.time() - t_phase,
                    "prune_history": hist, "gates_pruned": hyb.circuit.gate_counts(),
                    "params_pruned": hyb.n_trainable()})
        # control: MLP residual of similar size
        ctl = QFANet(**kw, q_kind="mlp").to(device)
        ctl.load_state_dict(model.state_dict(), strict=False)
        vM, _ = R.fit(ctl, tr, va, [(ctl.quantum_parameters(), 5e-3), (ctl.classical_parameters(), 2e-4)],
                      cfg["epochs_b"], max(10, cfg["epochs_b"] // 3), s, max_minutes=max_minutes)
        preds["mlp_residual"].append(inv(R.predict(ctl, test_idx)))
        rec["val_mlp_residual"] = vM
        # D: Quantum-Train
        if cfg["qt"]:
            t_phase = time.time()
            qtm = QFANet(**kw).to(device)
            qtm.circuit.mask.copy_(hyb.circuit.mask)
            names = qt_names(qtm)
            shapes = [dict(qtm.named_parameters())[n].shape for n in names]
            gen = QTGeneratorTorch(shapes).to(device)
            kept = [p for n, p in qtm.named_parameters() if n not in names]
            vQ, _ = R.fit(qtm, tr, va, [(list(gen.parameters()), 5e-3), (kept, 5e-3)],
                          2 * cfg["epochs_a"], 2 * cfg["patience_a"], s, gen, names, max_minutes=max_minutes)
            preds["qt_hybrid_pruned"].append(inv(R.predict(qtm, test_idx, gen, names)))
            n_kept = sum(p.numel() for n, p in qtm.named_parameters()
                         if n not in names and not n.startswith("circuit")) + qtm.circuit.n_active()
            rec.update({"sec_qt": time.time() - t_phase, "val_qt": vQ, "qt_qubits": gen.n, "qt_generated": gen.P,
                        "qt_trained": gen.n_trainable() + n_kept})
            # materialise: copy generated weights into an ordinary model (no quantum needed for them)
            with torch.no_grad():
                for n, t in gen.as_dict(names).items():
                    dict(qtm.named_parameters())[n].copy_(t)
            rec["qt_materialised_equal"] = bool(np.allclose(R.predict(qtm, test_idx), preds["qt_hybrid_pruned"][-1]
                                                            if tt == "classification" else
                                                            P.y(preds["qt_hybrid_pruned"][-1]), atol=1e-4))
        info["per_seed"].append(rec)
        log(f"  seed {s}: val A {vA:.4f}  B {vB:.4f}  pruned {hist[-1][1]:.4f} ({hist[-1][0]}/{hist[0][0]})  "
            f"mlp {vM:.4f}  [{time.time() - t_start:.0f}s]")
    ytest = y[test_idx]
    info["test"] = {k: metric(tt, ytest, np.mean(v, axis=0)) for k, v in preds.items() if v}
    # RandomForest on the same descriptors (sanity check against MatBench's RF entries)
    from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
    rf = (RandomForestRegressor if tt == "regression" else RandomForestClassifier)(n_estimators=300, n_jobs=-1, random_state=0)
    rf.fit(X_desc[train_all], y[train_all])
    p = rf.predict(X_desc[test_idx]) if tt == "regression" else rf.predict_proba(X_desc[test_idx])[:, 1]
    info["test"]["rf_descriptors"] = metric(tt, ytest, p)
    info["seconds"] = time.time() - t_start
    return info
